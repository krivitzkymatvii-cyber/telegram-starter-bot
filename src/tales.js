// Кличний відмінок лише для відомих або безпечних закінчень; інакше без звертання
const VOC = { Матвій: "Матвію", Юстинка: "Юстинко", Юстина: "Юстино", Толік: "Толіку", Вова: "Вово", Юля: "Юлю", Надя: "Надю", Надія: "Надіє", Люда: "Людо", Катя: "Катю" }

export function vocative(name) {
  const n = String(name || "").trim()
  if (!/^[А-ЯІЇЄҐ][а-яіїєґ'’ʼ-]{1,19}$/.test(n)) return ""
  if (VOC[n]) return VOC[n]
  if (/ій$/.test(n)) return n.slice(0, -2) + "ію"
  if (/ія$/.test(n)) return n.slice(0, -2) + "іє"
  if (/ка$/.test(n)) return n.slice(0, -1) + "о"
  if (/я$/.test(n)) return n.slice(0, -1) + "ю"
  return ""
}

export function formatTale(i, name) {
  const t = TALES[i]
  const v = vocative(name)
  return `📖 ${t.title}\n\n${t.text}\n\n🌙 ${v ? `Солодких снів, ${v}!` : "Солодких снів!"}`
}

// не повторюємо останню казку в чаті
export function nextIndex(chat) {
  let i
  do {
    i = Math.floor(Math.random() * TALES.length)
  } while (TALES.length > 1 && i === chat.lastTale)
  return i
}

export const taleKeyboard = () => ({ inline_keyboard: [[{ text: "📖 Казка на вечір", callback_data: "tale" }]] })

// Чи варто показувати кнопку під сповіщенням: вечірнє чи нічне відключення від години
export function wantsTaleButton(ev) {
  const h = Math.floor((ev.s % 1440) / 60)
  return (h >= 17 || h < 5) && ev.e - ev.s >= 60
}

async function sendTale(ctx, argText) {
  const chat = ensureChat(ctx.chat.id)
  const arg = (argText || "").trim()

  if (/^(список|list)$/i.test(arg)) {
    return ctx.reply("📚 Казки:\n\n" + TALES.map((t, i) => `${i + 1}. ${t.title}`).join("\n") + "\n\nОберіть: /kazka 3")
  }

  let i
  let name = ""
  const num = arg.match(/^(\d{1,2})(?:\s+(\S+))?$/)

  if (num && +num[1] >= 1 && +num[1] <= TALES.length) {
    i = +num[1] - 1
    name = num[2] || ""
  } else {
    i = nextIndex(chat)
    name = arg
  }

  chat.lastTale = i
  save()
  await ctx.reply(formatTale(i, name))
}

export function registerTales(bot) {
  bot.command("kazka", (ctx) => sendTale(ctx, ctx.match))

  bot.callbackQuery("tale", async (ctx) => {
    await ctx.answerCallbackQuery()
    await sendTale(ctx, "")
  })
}
