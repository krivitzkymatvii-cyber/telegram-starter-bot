// Православна Пасха (юліанська пасхалія) -> григоріанська дата (1900–2099)
export function orthodoxEaster(year) {
  const a = year % 4, b = year % 7, c = year % 19
  const d = (19 * c + 15) % 30
  const e = (2 * a + 4 * b - d + 34) % 7
  const month = Math.floor((d + e + 114) / 31)
  const day = ((d + e + 114) % 31) + 1
  const ms = Date.UTC(year, month - 1, day) + 13 * 86400000
  return Math.floor(ms / 86400000) // dayNum
}

// n-й день тижня (0=нд..6=сб) у місяці
function nthWeekday(year, month, wd, n) {
  const first = new Date(Date.UTC(year, month - 1, 1)).getUTCDay()
  const day = 1 + ((wd - first + 7) % 7) + (n - 1) * 7
  return Math.floor(Date.UTC(year, month - 1, day) / 86400000)
}

export function holidaysFor(dayNum) {
  const dt = new Date(dayNum * 86400000)
  const y = dt.getUTCFullYear()
  const out = []

  const f = fixed[key(dt.getUTCMonth() + 1, dt.getUTCDate())]
  if (f) out.push(f)

  const easter = orthodoxEaster(y)
  if (dayNum === easter) out.push("🥚 Христос Воскрес! З Великоднем! Воістину Воскрес!")
  if (dayNum === easter + 49) out.push("🌿 З Трійцею!")
  if (dayNum === nthWeekday(y, 5, 0, 2)) out.push("💐 З Днем матері! Обійміть найдорожчу людину.")
  if (dayNum === nthWeekday(y, 5, 4, 3)) out.push("🧵 З Днем вишиванки!")

  return out
}

