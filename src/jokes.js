// Жарт до зміни графіка: порівнюємо старі й нові інтервали [[початок, кінець], ...]
export function jokeChange(oldIntervals, newIntervals) {
  if (!jokesEnabled()) return ""
  if (!newIntervals.length) return pick("cancelled", P.cancelled)

  const a = total(oldIntervals)
  const b = total(newIntervals)
  if (b < a) return pick("reduced", P.reduced)
  if (b > a) return pick("increased", P.increased)
  return pick("shifted", P.shifted)
}

