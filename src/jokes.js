const last = new Map() // щоб один і той самий жарт не йшов двічі поспіль

export function pick(name, pool) {
  if (pool.length === 1) return pool[0]
  let i
  do {
    i = Math.floor(Math.random() * pool.length)
  } while (i === last.get(name))
  last.set(name, i)
  return pool[i]
}

