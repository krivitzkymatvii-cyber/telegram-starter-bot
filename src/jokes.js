// Коментарі до повітряної тривоги.
export function jokeAlarm(type) {
  if (!jokesEnabled()) return ""
  if ((process.env.ALARM_JOKES || "").trim().toLowerCase() === "off") return ""
  const name = { start: "alarmStart", escalate: "alarmEscalate", end: "alarmEnd" }[type]
  return name ? pick(name, P[name]) : ""
}

const total = (iv) => iv.reduce((s, [a, b]) => s + (b - a), 0)

// Жарт перед відключенням: враховує тривалість, годину початку й вихідні
export function jokeBefore({ s, e }) {
  if (!jokesEnabled()) return ""

  const dur = e - s
  const hour = Math.floor((s % 1440) / 60)
  const { dayNum } = kyivNow()
  const weekday = new Date((dayNum + Math.floor(s / 1440)) * 86400000).getUTCDay()

  const cats = [["before", 3]]
  if (dur <= 90) cats.push(["beforeShort", 4])
  if (dur >= 240) cats.push(["beforeLong", 4])
  if (hour >= 22 || hour < 6) cats.push(["beforeNight", 4])
  else if (hour < 10) cats.push(["beforeMorning", 3])
  else if (hour < 17) cats.push(["beforeDay", 3])
  else cats.push(["beforeEvening", 3])
  if (weekday === 0 || weekday === 6) cats.push(["beforeWeekend", 2])

  const name = weighted(cats)
  return pick(name, P[name])
}

// Жарт, коли світло має повернутися (ev.e: час закінчення в хвилинах)
export function jokeBack(ev) {
  if (!jokesEnabled()) return ""

  const hour = Math.floor(((ev?.e ?? 720) % 1440) / 60)
  const cats = [["back", 4]]
  if (hour >= 22 || hour < 6) cats.push(["backNight", 4])
  else if (hour >= 17) cats.push(["backEvening", 3])

  const name = weighted(cats)
  return pick(name, P[name])
}

