// Коментарі до повітряної тривоги. Вимкнути: ALARM_JOKES=off (або JOKES=off).
export function jokeAlarm(type) {
  if (!jokesEnabled()) return ""
  if ((process.env.ALARM_JOKES || "").trim().toLowerCase() === "off") return ""
  const name = { start: "alarmStart", escalate: "alarmEscalate", end: "alarmEnd" }[type]
  return name ? pick(name, P[name]) : ""
}

const total = (iv) => iv.reduce((s, [a, b]) => s + (b - a), 0)

export function jokeBefore({ s, e }) {
  if (!jokesEnabled()) return ""
  const dur = e - s
  const startHour = Math.floor((s % 1440) / 60)

  const roll = Math.random()
  let name = "before"
  if (dur <= 90 && roll < 0.7) name = "beforeShort"
  else if (dur >= 240 && roll < 0.7) name = "beforeLong"
  else if ((startHour >= 22 || startHour < 6) && roll < 0.7) name = "beforeNight"
  else if (startHour >= 6 && startHour < 10 && roll < 0.5) name = "beforeMorning"

  return pick(name, P[name])
}

export const jokeBack = () => (jokesEnabled() ? pick("back", P.back) : "")

// Жарт до публікації графіка, де відключень немає
export const jokeNoOutages = () =>
  jokesEnabled() ? pick("noOutages", P.noOutages) : ""

// Жарт до зміни графіка: порівнюємо старі й нові інтервали [[початок, кінець], ...]
export function jokeChange(oldIntervals, newIntervals) {
  if (!jokesEnabled()) return ""
  if (!newIntervals.length) return pick("cancelled", P.cancelled)

  const a = total(oldIntervals)
  const b = total(newIntervals)
  if (b < a) return pick("reduced", P.reduced)
  if (b > a) return pick("increased", P.increased)
  return pick("shifted", P.shifted)
}

